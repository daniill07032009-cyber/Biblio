def bunker_random_age(negative=False, rare_roll=None, age_roll=None):
    """Return an age; the 500–3000-year anomaly has a 0.1% chance."""
    from secrets import randbelow
    rare_roll = randbelow(1000) if rare_roll is None else rare_roll
    if rare_roll == 0:
        return randbelow(2501) + 500
    age_roll = randbelow(1000) if age_roll is None else age_roll
    if negative:
        if age_roll < 500:
            return randbelow(15) + 1
        return randbelow(41) + 80
    return randbelow(64) + 16



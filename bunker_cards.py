"""Large, deterministic card catalogs for BunkerOnline.

Catalog entries are generated from domain-specific combinations so every option is
unique, reproducible, and available without external services.
"""

from itertools import product


def _unique_combinations(left, right, limit):
    result = []
    seen = set()
    for first, second in product(left, right):
        value = f"{first} — {second}"
        if value not in seen:
            seen.add(value)
            result.append(value)
            if len(result) == limit:
                return result
    return result


